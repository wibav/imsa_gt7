const LOCALES = { es: 'es-ES', en: 'en-GB', pt: 'pt-PT' };

/** Texto del menú de sala en el idioma pedido (o el original si no hay traducción). */
export function traducirSala(texto, lang = 'es') {
    if (lang === 'es' || texto == null) return texto;
    return SALA[lang]?.[texto] ?? texto;
}

export const frasesSala = (lang = 'es') => FRASES[lang] || FRASES.es;
export const localeSala = (lang = 'es') => LOCALES[lang] || LOCALES.es;
